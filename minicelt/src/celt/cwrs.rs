//! Port of celt/cwrs.c (encoder side, static pulse cache: no SMALL_FOOTPRINT, no CUSTOM_MODES).

use super::arch::Ix;
use super::arch::{IMAX, IMIN};
use super::entcode::ec_enc;
use super::entenc::ec_enc_uint;
use core::cell::UnsafeCell;

/*For each V(N,K) supported, we will access element U(min(N,K+1),max(N,K+1)).
  Thus, the number of entries in row I is the larger of the maximum number of
   pulses we will ever allocate for a given N=I (K=128, or however many fit in
   32 bits, whichever is smaller), plus one, and the maximum N for which
   K=I-1 pulses fit in 32 bits.
  Otherwise, we can limit things to the set of N which can be achieved by
   splitting a band from a standard Opus mode: 176, 144, 96, 88, 72, 64, 48,
   44, 36, 32, 24, 22, 18, 16, 8, 4, 2).
  CELT_PVQ_U_ROW holds the offsets of the rows in CELT_PVQ_U_DATA (CWRS_EXTRA_ROWS undefined). */
/// The `CELT_PVQ_U_DATA` table of celt/cwrs.c, generated by `init_cwrs` instead of stored in the
/// binary (it lives in `.bss`).
struct PvqU(UnsafeCell<[u32; 1272]>);
// SAFETY: written only by `init_cwrs`, single-threaded use only (as the pseudostack).
unsafe impl Sync for PvqU {}
static CELT_PVQ_U_DATA: PvqU = PvqU(UnsafeCell::new([0; 1272]));
static CELT_PVQ_U_ROW: [u16; 15] = [0, 176, 351, 525, 698, 870, 1041, 1131, 1178, 1207, 1226, 1240, 1248, 1254, 1257];
/// Last column `b` of the entries `U(a, b)` stored in row `a` (position `ROW[a] + b`); the
/// stored rows overlap, with equal values where they do.
static CELT_PVQ_U_LAST: [u8; 15] = [176, 176, 176, 176, 176, 176, 96, 54, 37, 28, 24, 19, 18, 16, 14];

/// Fills `CELT_PVQ_U_DATA`: `U(0,b) = [b == 0]` (the table's convention), `U(a,0) = 0` and
/// `U(a,b) = U(a-1,b) + U(a,b-1) + U(a-1,b-1)` modulo 2^32 for a > 0, row by row. Reproduces
/// the C table entry for entry (checked against the table of celt/cwrs.c when this was
/// written; the other C entries are never read).
pub fn init_cwrs() {
    // SAFETY: nothing reads the table while it is rebuilt (init only).
    let data = unsafe { &mut *CELT_PVQ_U_DATA.0.get() };
    let mut row = [0u32; 177];
    row[0] = 1;
    for a in 0..15usize {
        if a > 0 {
            let mut diag = row[0];
            row[0] = 0;
            for b in 1..177 {
                let old = row[b];
                row[b] = old.wrapping_add(row[b - 1]).wrapping_add(diag);
                diag = old;
            }
        }
        let (r, last) = (CELT_PVQ_U_ROW[a] as usize, CELT_PVQ_U_LAST[a] as usize);
        data[r + a..=r + last].copy_from_slice(&row[a..=last]);
    }
}

/*U(N,K) = U(K,N) := N>0?K>0?U(N-1,K)+U(N,K-1)+U(N-1,K-1):0:K>0?1:0*/
#[inline(always)]
fn CELT_PVQ_U(_n: i32, _k: i32) -> u32 {
    // IX-HARD: both indices come from `n`/`k` through the ROW table (`ROW[min] + max`), so there is no
    // length the compiler could prove them against: keep `Ix` (this is on the PVQ encode path).
    // SAFETY: init_cwrs ran before the first encode; the table is only read here.
    unsafe { (*CELT_PVQ_U_DATA.0.get()).at(CELT_PVQ_U_ROW.at(IMIN(_n, _k) as usize) as usize + IMAX(_n, _k) as usize) }
}

/*V(N,K) := U(N,K)+U(N,K+1) = the number of PVQ codewords for a band of size N
   with K pulses allocated to it.*/
#[inline(always)]
fn CELT_PVQ_V(_n: i32, _k: i32) -> u32 {
    CELT_PVQ_U(_n, _k) + CELT_PVQ_U(_n, _k + 1)
}

// IX-HARD: `_y[.._n]` re-slice measured +55 bytes, +2 `unreachable`: the slice check, and the compiler cannot
// prove the `j -= 1` below stays in range of `_n` (the loop exits on `j == 0`).
fn icwrs(_n: i32, _y: &[i32]) -> u32 {
    debug_assert!(_n >= 2);
    let mut j = (_n - 1) as usize;
    let mut i: u32 = (_y.at(j) < 0) as u32;
    let mut k = _y.at(j).abs();
    loop {
        j -= 1;
        i += CELT_PVQ_U(_n - j as i32, k);
        k += _y.at(j).abs();
        if _y.at(j) < 0 {
            i += CELT_PVQ_U(_n - j as i32, k + 1);
        }
        if j == 0 {
            break;
        }
    }
    i
}

/// Fixed interface (used by vq.rs): encodes the pulse vector `_y[..N]` with `K` pulses.
pub fn encode_pulses(_y: &[i32], N: i32, K: i32, enc: &mut ec_enc) {
    debug_assert!(K > 0);
    ec_enc_uint(enc, icwrs(N, _y), CELT_PVQ_V(N, K));
}
